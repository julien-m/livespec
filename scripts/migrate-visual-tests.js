#!/usr/bin/env node
// @spec FR-023: --scan lists features without visual tests — .specs/features/010-visual-testing-complete/spec.md#fr-023
// @spec FR-024: --generate creates test files for missing features — spec.md#fr-024
// @spec FR-025: Creates baseline directories for each feature — spec.md#fr-025
//
// Usage:
//   node scripts/migrate-visual-tests.js --scan           # List features without visual tests
//   node scripts/migrate-visual-tests.js --generate       # Create test files for missing features
//   node scripts/migrate-visual-tests.js --dry-run        # Preview without creating files (exit 0)

import { existsSync, readdirSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { join, basename } from 'path';

const SPECS_DIR = '.specs/features';
const TESTS_VISUAL_DIR = 'tests/visual';

// EC-007: UI heuristic keywords — features without these are likely backend-only
const UI_KEYWORDS = [
  'button', 'modal', 'form', 'page', 'layout', 'screen', 'component', 'view',
  'dialog', 'panel', 'sidebar', 'navbar', 'footer', 'header', 'menu', 'input',
  'table', 'chart', 'dashboard', 'toast', 'alert', 'card', 'list', 'grid',
  'animation', 'transition', 'responsive', 'viewport', 'mobile', 'tablet',
];

// @spec FR-025: Baseline directories to create per feature — spec.md#fr-025
const BASELINE_DIRS = ['mockups', 'fullpage', 'mobile', 'tablet', 'desktop', 'animations'];

function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function hasUIKeywords(content) {
  const lower = content.toLowerCase();
  return UI_KEYWORDS.some(kw => lower.includes(kw));
}

function matchedUIKeywords(content) {
  const lower = content.toLowerCase();
  return UI_KEYWORDS.filter(kw => lower.includes(kw));
}

function scanFeatures() {
  if (!existsSync(SPECS_DIR)) {
    console.error(`Missing .specs/features/ directory. Is this a LiveSpec project?`);
    process.exit(1);
  }

  const features = readdirSync(SPECS_DIR, { withFileTypes: true })
    .filter(e => e.isDirectory())
    .map(e => e.name);

  return features.map(featureDir => {
    const specPath = join(SPECS_DIR, featureDir, 'spec.md');
    const slug = slugify(featureDir.replace(/^\d+-/, ''));
    const testPath = join(TESTS_VISUAL_DIR, `${featureDir}.spec.ts`);
    const testPathSlug = join(TESTS_VISUAL_DIR, `${slug}.spec.ts`);

    let hasUI = false;
    let keywords = [];
    let specContent = '';

    if (existsSync(specPath)) {
      specContent = readFileSync(specPath, 'utf-8');
      keywords = matchedUIKeywords(specContent);
      hasUI = keywords.length > 0;
    }

    const hasTests = existsSync(testPath) || existsSync(testPathSlug);

    return {
      dir: featureDir,
      slug,
      testPath,
      hasSpec: existsSync(specPath),
      hasUI,
      keywords,
      hasTests,
      action: hasUI && !hasTests ? 'GENERATE' : hasTests ? 'SKIP (has tests)' : !hasUI ? 'SKIP (no UI)' : 'OK',
    };
  });
}

function generateTestTemplate(feature) {
  const { dir, slug } = feature;
  // Read title from spec.md if available
  let title = dir;
  const specPath = join(SPECS_DIR, dir, 'spec.md');
  if (existsSync(specPath)) {
    const match = readFileSync(specPath, 'utf-8').match(/^title:\s*["']?(.+?)["']?\s*$/m);
    if (match) title = match[1];
  }

  return `import { test, expect } from '@playwright/test';
import { existsSync } from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';

// Visual tests for: ${title}
// Feature: ${dir}
// Generated by: scripts/migrate-visual-tests.js
// TODO: Replace placeholder selectors and routes with actual values

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const FEATURE = '${slug}';
const MOCKUP_DIR = path.join(__dirname, '../../baselines/mockups', FEATURE);
const TOLERANCE = 0.02;

test.describe('Visual tests: ${title}', () => {
  test('renders correctly (mockup comparison)', async ({ page }) => {
    const mockupPath = path.join(MOCKUP_DIR, 'main.png');
    if (!existsSync(mockupPath)) {
      test.skip(true, \`TODO: Add mockup baseline at \${mockupPath}\`);
      return;
    }
    // TODO: Replace with actual route
    await page.goto('/TODO-replace-with-actual-route');
    await page.waitForLoadState('networkidle');
    await expect(page.locator('[data-testid="TODO-replace-selector"]')).toHaveScreenshot(
      'main.png',
      { maxDiffPixelRatio: TOLERANCE, animations: 'disabled' }
    );
  });

  // TODO: Add more test cases based on spec.md stories
  // See docs/visual-testing/mockup-workflow.md for the full workflow
});
`;
}

// @spec FR-006: Emit structured sentinel from --generate — .specs/features/011-visual-migrate-integration/spec.md#fr-006
function generateTests(features, dryRun) {
  const toGenerate = features.filter(f => f.hasUI && !f.hasTests);

  if (toGenerate.length === 0) {
    console.log('All UI features already have visual tests. Nothing to generate.');
    // @spec FR-006: Always emit sentinel on --generate (even for 0 files) — spec.md#fr-006
    if (!dryRun) {
      console.log('VISUAL_SCAFFOLD_RESULT: files=0 dirs=0');
    }
    process.exit(0);
  }

  console.log(`\n${dryRun ? '[DRY RUN] Would generate' : 'Generating'} ${toGenerate.length} test file(s):\n`);

  let generated = 0;
  let dirsCreated = 0;
  let skipped = 0;

  for (const feature of toGenerate) {
    const testContent = generateTestTemplate(feature);

    if (dryRun) {
      console.log(`  [WOULD CREATE] ${feature.testPath}`);
      // @spec FR-025: Show baseline directories that would be created
      for (const dir of BASELINE_DIRS) {
        console.log(`  [WOULD CREATE DIR] baselines/${dir}/${feature.slug}/`);
      }
    } else {
      // @spec AC-030: Hard guard — never overwrite existing tests — spec.md#ac-030
      if (existsSync(feature.testPath)) {
        console.log(`  [SKIP] ${feature.testPath} already exists (preserved)`);
        skipped++;
        continue;
      }

      // Create test file
      mkdirSync(TESTS_VISUAL_DIR, { recursive: true });
      writeFileSync(feature.testPath, testContent);
      console.log(`  [CREATED] ${feature.testPath}`);

      // @spec FR-005: Create baseline directories — .specs/features/011-visual-migrate-integration/spec.md#fr-005
      for (const dir of BASELINE_DIRS) {
        const baselineDir = join('baselines', dir, feature.slug);
        const baselineDirExists = existsSync(baselineDir);
        mkdirSync(baselineDir, { recursive: true });
        // Add .gitkeep so empty dirs are committed
        const gitkeep = join(baselineDir, '.gitkeep');
        if (!existsSync(gitkeep)) {
          writeFileSync(gitkeep, '');
        }
        if (!baselineDirExists) {
          dirsCreated++;
        }
      }
      console.log(`  [CREATED DIRS] baselines/{${BASELINE_DIRS.join(',')}}/${feature.slug}/`);
      generated++;
    }
  }

  if (!dryRun) {
    console.log(`\nSummary: ${generated} test file(s) generated, ${skipped} skipped (existing tests preserved)`);
    console.log('\nNext steps:');
    console.log('  1. Export Figma mockups to baselines/mockups/<feature>/ for each generated test');
    console.log('  2. Update TODO placeholders in generated test files (routes, selectors)');
    console.log('  3. Run: npx playwright test --update-snapshots to create initial baselines');

    // @spec FR-006: Structured sentinel line for command-layer parsing — spec.md#fr-006
    console.log(`VISUAL_SCAFFOLD_RESULT: files=${generated} dirs=${dirsCreated}`);
  }

  process.exit(0);
}

function printScanTable(features) {
  console.log('\nFeature Migration Scan\n');
  console.log('Feature                          | Has UI | Has Tests | Action');
  console.log('--------------------------------|--------|-----------|-------------------');
  for (const f of features) {
    const name = f.dir.padEnd(32).slice(0, 32);
    const hasUI = f.hasUI ? '  YES ' : '   NO ';
    const hasTests = f.hasTests ? '   YES  ' : '    NO  ';
    console.log(`${name}|${hasUI}  |${hasTests} | ${f.action}`);
  }

  const needTests = features.filter(f => f.hasUI && !f.hasTests).length;
  const totalUI = features.filter(f => f.hasUI).length;
  console.log(`\n${totalUI} UI feature(s), ${needTests} without visual tests`);
  if (needTests > 0) {
    console.log(`Run with --generate to scaffold test files, or --dry-run to preview`);
  }
}

// Main
const args = process.argv.slice(2);
const scan = args.includes('--scan');
const generate = args.includes('--generate');
const dryRun = args.includes('--dry-run');

if (!scan && !generate && !dryRun) {
  console.log('Usage:');
  console.log('  node scripts/migrate-visual-tests.js --scan       # List features without visual tests');
  console.log('  node scripts/migrate-visual-tests.js --generate   # Create test files for missing features');
  console.log('  node scripts/migrate-visual-tests.js --dry-run    # Preview without creating files');
  process.exit(1);
}

const features = scanFeatures();

if (scan) {
  printScanTable(features);
  process.exit(0);
}

if (dryRun || generate) {
  printScanTable(features);
  generateTests(features, dryRun);
}
