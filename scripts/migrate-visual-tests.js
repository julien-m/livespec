function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function matchedUIKeywords(content) {
  const lower = content.toLowerCase();
  return UI_KEYWORDS.filter(kw => lower.includes(kw));
}

// Cache of { surfaceId → [{ slug, route }] } built lazily from surfaces' routesDir
const ROUTE_EXTS = ['.tsx', '.jsx', '.vue', '.ts', '.js'];
const ROUTE_SUBDIR_CANDIDATES = ['app/routes', 'src/app/routes', 'src/routes', 'src/pages', 'pages'];
let _surfaceRoutesCache = null;

function listSurfaceRoutes() {
  if (_surfaceRoutesCache) return _surfaceRoutesCache;
  const all = [];
  for (const surface of SURFACES) {
    const dirs = new Set();
    if (surface.routesDir && existsSync(surface.routesDir)) dirs.add(surface.routesDir);
    for (const sub of ROUTE_SUBDIR_CANDIDATES) {
      const dir = surface.path && surface.path !== '.' ? join(surface.path, sub) : sub;
      if (existsSync(dir)) dirs.add(dir);
    }
    for (const dir of dirs) {
      try {
        for (const file of readdirSync(dir)) {
          if (file.startsWith('_') || file.startsWith('.')) continue;
          if (!ROUTE_EXTS.some(ext => file.endsWith(ext))) continue;
          const fileSlug = file.replace(/\.(tsx|jsx|vue|ts|js)$/, '');
          const route = fileSlug === 'index' ? '/' : `/${fileSlug}`;
          all.push({ slug: fileSlug, route, dir, surfaceId: surface.id });
        }
      } catch { /* skip unreadable dir */ }
    }
  }
  _surfaceRoutesCache = all;
  return all;
}

// Match a feature slug against actual route files discovered in surfaces' routesDir
function findRouteInSurfaces(slug) {
  const routes = listSurfaceRoutes();
  if (routes.length === 0) return null;

  const exact = routes.find(r => r.slug === slug);
  if (exact) return exact.route;

  const slugMatch = routes.find(r => slug === r.slug || slug.endsWith(`-${r.slug}`) || slug.startsWith(`${r.slug}-`));
  if (slugMatch) return slugMatch.route;

  const partial = routes.find(r => r.slug !== 'index' && (slug.includes(r.slug) || r.slug.includes(slug)));
  if (partial) return partial.route;

  return null;
}

// Infer the most likely URL route from a feature slug + spec content.
// Resolution order:
//   1. Actual route file in any configured surface's routesDir (authoritative)
//   2. ROUTE_MAP slug heuristic (legacy fallback)
//   3. Backtick-quoted /path in spec content
//   4. Default '/'
function inferRouteFromFeature(slug, specPath) {
  const surfaceRoute = findRouteInSurfaces(slug);
  if (surfaceRoute) return surfaceRoute;

  if (ROUTE_MAP[slug]) return ROUTE_MAP[slug];
  for (const [key, route] of Object.entries(ROUTE_MAP)) {
    if (slug.includes(key)) return route;
  }
  if (specPath && existsSync(specPath)) {
    const content = readFileSync(specPath, 'utf-8');
    const matches = content.match(/`(\/[a-z][a-z0-9\-/]*)`/g) || [];
    for (const match of matches) {
      const route = match.replace(/`/g, '');
      if (!route.startsWith('/api') && !route.startsWith('/ws')) {
        return route;
      }
    }
  }
  return '/';
}

// Find the best-matching Pencil mockup filename for a feature slug
// Searches .specs/design/screens/ for current-NN-{slug}-desktop.png
function inferMockupFilename(slug, viewport = 'desktop') {
  if (!existsSync(PENCIL_MOCKUP_DIR)) {
    return `current-01-${slug}-${viewport}.png`;
  }
  const files = readdirSync(PENCIL_MOCKUP_DIR);
  // Look for: current-NN-*{slug}*-{viewport}.png
  const pattern = new RegExp(`current-\\d+-.*${slug}.*-${viewport}\\.png`, 'i');
  const match = files.find(f => pattern.test(f));
  if (match) return match;
  // Also try without slug (first current-* file if only one screen)
  const fallback = files.find(f => /^current-.*\.png$/i.test(f) && f.includes(viewport));
  if (fallback) return fallback;
  return `current-01-${slug}-${viewport}.png`;
}

function scanFeatures() {
  if (!existsSync(SPECS_DIR)) {
    console.error(`Missing .specs/features/ directory. Is this a LiveSpec project?`);
    process.exit(1);
  }

  const features = readdirSync(SPECS_DIR, { withFileTypes: true })
    .filter(e => e.isDirectory())
    .map(e => e.name);

  return features.map(featureDir => {
    const specPath = join(SPECS_DIR, featureDir, 'spec.md');
    const slug = slugify(featureDir.replace(/^\d+-/, ''));

    // Check all possible test locations
    const testPathLegacy = join(LEGACY_TESTS_DIR, `${featureDir}.spec.ts`);
    const testPathLegacySlug = join(LEGACY_TESTS_DIR, `${slug}.spec.ts`);
    const testPathE2E = join(FRONTEND_E2E_DIR, `${featureDir}.spec.ts`);
    const testPathE2ESlug = join(FRONTEND_E2E_DIR, `${slug}.spec.ts`);
    // Feature-number-prefixed variant (NNN-slug.spec.ts)
    const featureNum = featureDir.match(/^(\d+)/)?.[1];
    const testPathE2ENum = featureNum ? join(FRONTEND_E2E_DIR, `${featureNum}-${slug}.spec.ts`) : null;

    const targetTestPath = join(TEST_DIR, `${featureDir}.spec.ts`);

    let hasUI = false;
    let keywords = [];

    if (existsSync(specPath)) {
      const specContent = readFileSync(specPath, 'utf-8');
      keywords = matchedUIKeywords(specContent);
      hasUI = keywords.length > 0;
    }

    const hasTests = existsSync(testPathLegacy) || existsSync(testPathLegacySlug) ||
      existsSync(testPathE2E) || existsSync(testPathE2ESlug) ||
      (testPathE2ENum && existsSync(testPathE2ENum));

    return {
      dir: featureDir,
      slug,
      specPath,
      testPath: targetTestPath,
      hasSpec: existsSync(specPath),
      hasUI,
      keywords,
      hasTests,
      action: hasUI && !hasTests ? 'GENERATE' : hasTests ? 'SKIP (has tests)' : !hasUI ? 'SKIP (no UI)' : 'OK',
    };
  });
}

// ─── Analysis helpers: extract patterns from existing tests ─────────────────

function detectFixturesFromDir(testDir) {
  const fixturesPath = join(testDir, 'fixtures.ts');
  if (!existsSync(fixturesPath)) return { authenticated: null, empty: null };
  const content = readFileSync(fixturesPath, 'utf-8');
  const authenticated =
    content.match(/export (?:const|(?:async )?function) (mock\w*[Aa]uth\w*)/)?.[1] ?? null;
  const empty =
    content.match(/export (?:const|(?:async )?function) (mock\w*[Ee]mpty\w*)/)?.[1] ?? null;
  return { authenticated, empty };
}

function extractSelectorsFromExistingTests(testDir) {
  if (!existsSync(testDir)) return [];
  // Only scan non-generated tests (exclude NNN-prefixed files) to get project-specific selectors
  const testFiles = readdirSync(testDir)
    .filter(f => f.endsWith('.spec.ts') && !f.match(/^\d{3}-/));
  const selectors = [];
  for (const file of testFiles) {
    const content = readFileSync(join(testDir, file), 'utf-8');
    // Class selectors — most specific (e.g. .desktop-header)
    for (const m of content.matchAll(/page\.locator\(['"](\.[a-z][a-z0-9-]+)['"]\)/gi)) {
      selectors.push({ selector: m[1], priority: 10 });
    }
    // data-testid selectors
    for (const m of content.matchAll(/page\.locator\(['"]\[data-testid="([^"]+)"\]['"]\)/gi)) {
      selectors.push({ selector: `[data-testid="${m[1]}"]`, priority: 8 });
    }
    // Element selectors — least specific (e.g. header, nav)
    for (const m of content.matchAll(/page\.locator\(['"]([a-z]+)['"]\)/gi)) {
      selectors.push({ selector: m[1], priority: 5 });
    }
  }
  return selectors
    .sort((a, b) => b.priority - a.priority)
    .map(s => s.selector)
    .filter((s, i, arr) => arr.indexOf(s) === i) // dedupe, keeping highest priority
    .slice(0, 10);
}

function extractWaitPatterns(testDir) {
  if (!existsSync(testDir)) return { ssr: null };
  const testFiles = readdirSync(testDir).filter(f => f.endsWith('.spec.ts'));
  for (const file of testFiles) {
    const content = readFileSync(join(testDir, file), 'utf-8');
    const m = content.match(/await page\.waitForFunction\([\s\S]+?\{ timeout: \d[\d_]* \},\s*\);/);
    if (m) return { ssr: m[0] };
  }
  return { ssr: null };
}

function extractCommonTestCases(testDir) {
  if (!existsSync(testDir)) return [];
  const testFiles = readdirSync(testDir).filter(f => f.endsWith('.spec.ts'));
  const counts = {};
  for (const file of testFiles) {
    const content = readFileSync(join(testDir, file), 'utf-8');
    for (const m of content.matchAll(/test\(['"]([^'"]+)['"]/g)) {
      const name = m[1].toLowerCase();
      counts[name] = (counts[name] || 0) + 1;
    }
  }
  return Object.entries(counts)
    .filter(([, c]) => c >= 2)
    .map(([n]) => n);
}

function analyzeExistingTests(testDir) {
  return {
    fixtures: detectFixturesFromDir(testDir),
    selectors: extractSelectorsFromExistingTests(testDir),
    waitPatterns: extractWaitPatterns(testDir),
    commonTestCases: extractCommonTestCases(testDir),
  };
}

