// Spec-aware helpers

// Parse spec.md content + implementation.md for visual test generation context
function parseSpecContext(specContent) {
  if (!specContent) return { heading: null, route: null, acRows: [] };

  // Heading: frontmatter title > # Feature: X > # X
  let heading = null;
  const fmTitle = specContent.match(/^title:\s*["']?(.+?)["']?\s*$/m)?.[1];
  const h1 = specContent.match(/^# (?:Feature:\s*)?(.+)/m)?.[1];
  if (fmTitle) heading = fmTitle.replace(/^Feature:\s*/i, '').trim();
  else if (h1) heading = h1.replace(/^Feature:\s*/i, '').trim();

  // Route: first backtick page route in spec (skip /api, /ws)
  let route = null;
  for (const m of specContent.matchAll(/`(\/[a-z][a-z0-9/-]*)`/g)) {
    const r = m[1];
    if (!r.startsWith('/api') && !r.startsWith('/ws')) { route = r; break; }
  }

  // ACs from markdown table rows: | AC-NNN | Description | ... |
  const acRows = [...specContent.matchAll(/\|\s*(AC-\d+)\s*\|\s*([^|]{5,}?)\s*\|/g)]
    .map(m => ({ id: m[1], description: m[2].trim() }))
    .filter(ac => !ac.description.startsWith('-') && !/^Criterion/i.test(ac.description));

  return { heading, route, acRows };
}

// Keywords that signal an AC has a visual output worth screenshotting
const VISUAL_AC_KEYWORDS = [
  'display', 'show', 'render', 'visible', 'appear', 'indicator',
  'card', 'panel', 'bar', 'state', 'layout', 'button', 'badge', 'view', 'list', 'grid',
];

// ACs covered by the 4 base tests — skip when building extras
const BASE_AC_PATTERNS = /empty state|mobile|responsive|viewport|touch target/i;

// Convert AC description → kebab screenshot name (max 5 words)
function acToScreenshotName(description) {
  return description
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .trim()
    .split(/\s+/)
    .slice(0, 5)
    .join('-') + '.png';
}

// Convert AC description → readable test name
function acToTestName(description) {
  return description.replace(/^(?:Dashboard |The )/i, '').replace(/\s{2,}/g, ' ').trim();
}

// Generate extra spec-aware test stubs from AC rows (max 3)
function buildSpecAwareTests(acRows) {
  if (!acRows || acRows.length === 0) return '';

  const extras = acRows
    .filter(ac => {
      const desc = ac.description.toLowerCase();
      if (!VISUAL_AC_KEYWORDS.some(kw => desc.includes(kw))) return false;
      if (BASE_AC_PATTERNS.test(ac.description)) return false;
      return true;
    })
    .slice(0, 3);

  if (extras.length === 0) return '';

  return '\n' + extras.map(ac => {
    const testName = acToTestName(ac.description);
    const screenshotName = acToScreenshotName(ac.description);
    return `  // ${ac.id}: ${ac.description}
  test('${testName}', async ({ page }) => {
    await page.goto(ROUTE, { waitUntil: 'networkidle' });
    await page.waitForFunction(
      (heading) => {
        const el = document.querySelector('h1, h2, [role="heading"]');
        return el?.textContent?.includes(heading);
      },
      HEADING,
      { timeout: 15_000 },
    );
    await page.waitForTimeout(1000);

    await expect(page).toHaveScreenshot('${screenshotName}', { fullPage: true });
  });`;
  }).join('\n\n') + '\n';
}

