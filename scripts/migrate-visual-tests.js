// @spec FR-006: Emit structured sentinel from --generate — .specs/features/011-visual-migrate-integration/spec.md#fr-006
function generateTests(features, dryRun) {
  const toGenerate = features.filter(f => f.hasUI && !f.hasTests);

  // Analyze existing tests once (reused by both spec-driven and route-scan)
  const analysis = FRONTEND_MODE ? analyzeExistingTests(TEST_DIR) : {};

  // Build covered routes from all spec-driven features
  const specCoveredRoutes = FRONTEND_MODE ? buildCoveredRoutes(features) : new Set();

  // Scan route files for uncovered pages
  const routesDir = FRONTEND_MODE ? detectRoutesDir() : null;
  if (FRONTEND_MODE && !routesDir) {
    console.log('[route-scan] No routes directory found — skipping route scan.');
  }
  const routeScanFeatures = routesDir
    ? scanRouteFiles(routesDir, specCoveredRoutes)
    : [];

  // Detect 404 page
  const notFoundFeature = routesDir ? detectNotFoundFromRoot(routesDir) : null;
  if (notFoundFeature && !specCoveredRoutes.has(notFoundFeature.route)) {
    routeScanFeatures.push(notFoundFeature);
  }

  // Early-exit only if NOTHING to generate (spec-driven AND route-scan)
  const totalToGenerate = toGenerate.length + routeScanFeatures.length;

  if (totalToGenerate === 0) {
    console.log('All UI features already have visual tests. Nothing to generate.');

    if (!dryRun) {
      console.log('\nChecking infrastructure:');
      ensurePlaywrightConfig(false);
      ensurePackageJsonScripts(false);
      // @spec FR-006: Always emit sentinel on --generate (even for 0 files) — spec.md#fr-006
      console.log('VISUAL_SCAFFOLD_RESULT: files=0 dirs=0 routes=0');
    }
    process.exit(0);
  }

  console.log(`\n${dryRun ? '[DRY RUN] Would generate' : 'Generating'} ${toGenerate.length} spec test(s) + ${routeScanFeatures.length} route test(s):\n`);

  let generated = 0;
  let skipped = 0;
  let dirsCreated = 0;
  let routeGenerated = 0;
  const featureList = [];

  if (!dryRun && FRONTEND_MODE) {
    console.log('🔍 Detected frontend/tests/e2e/ — using Pencil mockup mode');
    console.log('🧹 Cleaning up old migration artifacts...');
    cleanupOldMigration(false);
    mkdirSync(FRONTEND_E2E_DIR, { recursive: true });
  }

  // Phase 1: Spec-driven tests (AC-030: never overwrite numbered tests)
  for (const feature of toGenerate) {
    const testContent = generateTestTemplate(feature, analysis);

    if (dryRun) {
      console.log(`  [WOULD CREATE] ${feature.testPath}`);
      for (const dir of BASELINE_SUBDIRS) {
        console.log(`  [WOULD CREATE DIR] ${TEST_DIR}/baselines/${dir}/${feature.slug}/`);
      }
    } else {
      // @spec AC-030: Hard guard — never overwrite existing numbered tests — spec.md#ac-030
      if (existsSync(feature.testPath)) {
        console.log(`  [SKIP] ${feature.testPath} already exists (preserved)`);
        skipped++;
        continue;
      }

      mkdirSync(TEST_DIR, { recursive: true });
      writeFileSync(feature.testPath, testContent);
      console.log(`  [CREATED] ${feature.testPath}`);
      featureList.push(basename(feature.testPath));

      // Create baseline directories co-located with tests
      for (const dir of BASELINE_SUBDIRS) {
        const baselineDir = join(TEST_DIR, 'baselines', dir, feature.slug);
        mkdirSync(baselineDir, { recursive: true });
        const gitkeep = join(baselineDir, '.gitkeep');
        if (!existsSync(gitkeep)) writeFileSync(gitkeep, '');
        dirsCreated++;
      }
      console.log(`  [CREATED DIRS] ${TEST_DIR}/baselines/{${BASELINE_SUBDIRS.join(',')}}/${feature.slug}/`);

      generated++;
    }
  }

  // Phase 2: Route-scan tests (always overwrite — scaffold)
  const mergeResults = new Map(); // legacyPath → customBlocks[] for deletion guard
  if (routeScanFeatures.length > 0) {
    console.log(`\n🔍 Route scan (${routeScanFeatures.length} uncovered page(s)):`);
    for (const routeFeature of routeScanFeatures) {
      const mergeResult = generateRouteTest(routeFeature, analysis, dryRun);
      if (mergeResult?.legacyPath) {
        mergeResults.set(mergeResult.legacyPath, mergeResult.customBlocks);
      }
      if (!dryRun) routeGenerated++;
    }
  }

  // Phase 3: Build full covered routes set (spec + route-scan) for deletion check
  const allCoveredRoutes = new Set([...specCoveredRoutes]);
  for (const rf of routeScanFeatures) allCoveredRoutes.add(rf.route);

  // Phase 4: Delete superseded old tests (guarded by merge verification)
  deleteSupersededTests(allCoveredRoutes, dryRun, mergeResults);

  if (!dryRun) {
    console.log('\nChecking infrastructure:');
    const configUpdated = ensurePlaywrightConfig(false);
    const scriptsAdded = ensurePackageJsonScripts(false);

    printCompletionReport({ generated, skipped, configUpdated, scriptsAdded, featureList, routeGenerated });

    // @spec FR-006: Structured sentinel line for command-layer parsing — spec.md#fr-006
    console.log(`VISUAL_SCAFFOLD_RESULT: files=${generated} dirs=${dirsCreated} routes=${routeGenerated}`);
  } else {
    console.log('\n[DRY RUN] Infrastructure:');
    ensurePlaywrightConfig(true);
    ensurePackageJsonScripts(true);
    cleanupOldMigration(true);
  }

  process.exit(0);
}

function printScanTable(features) {
  const modeLabel = FRONTEND_MODE ? 'frontend/tests/e2e/' : 'tests/visual/';
  const mockupLabel = PENCIL_MODE ? '.specs/design/screens/' : `${TEST_DIR}/baselines/mockups/`;
  console.log(`\nFeature Migration Scan  [mode: ${modeLabel}]  [mockups: ${mockupLabel}]\n`);
  console.log('Feature                          | Has UI | Has Tests | Action');
  console.log('--------------------------------|--------|-----------|-------------------');
  for (const f of features) {
    const name = f.dir.padEnd(32).slice(0, 32);
    const hasUI = f.hasUI ? '  YES ' : '   NO ';
    const hasTests = f.hasTests ? '   YES  ' : '    NO  ';
    console.log(`${name}|${hasUI}  |${hasTests} | ${f.action}`);
  }

  const needTests = features.filter(f => f.hasUI && !f.hasTests).length;
  const totalUI = features.filter(f => f.hasUI).length;
  console.log(`\n${totalUI} UI feature(s), ${needTests} without visual tests`);
  if (needTests > 0) {
    console.log(`Run with --generate to scaffold test files, or --dry-run to preview`);
  }
}

// Main
const args = process.argv.slice(2);
const scan = args.includes('--scan');
const generate = args.includes('--generate');
const dryRun = args.includes('--dry-run');

if (!scan && !generate && !dryRun) {
  console.log('Usage:');
  console.log('  node scripts/migrate-visual-tests.js --scan       # List features without visual tests');
  console.log('  node scripts/migrate-visual-tests.js --generate   # Create test files for missing features');
  console.log('  node scripts/migrate-visual-tests.js --dry-run    # Preview without creating files');
  console.log('  node scripts/migrate-visual-tests.js --generate --force  # Bypass frontend detection');
  process.exit(1);
}

// @spec FR-010: Non-zero exit guard — a missing LiveSpec project is a more
// fundamental error than a missing frontend; surface it first so callers can
// distinguish "wrong directory" from "intentionally no frontend".
// Applies to every mode that consumes .specs/features/ (--generate, --dry-run, --scan).
// The inner scanFeatures() check is kept as a defensive guard for any future
// caller that reaches scanFeatures() without going through this top-level branch.
if ((generate || dryRun || scan) && !existsSync(SPECS_DIR)) {
  console.error(`Missing .specs/features/ directory. Is this a LiveSpec project?`);
  process.exit(1);
}

if (!hasWebFrontend && !args.includes('--force')) {
  console.log('\nNo web frontend detected — visual scaffolding skipped.');
  console.log('Use --force to generate anyway (e.g. projects using Playwright without a JS framework).');
  if (generate) {
    console.log('VISUAL_SCAFFOLD_RESULT: files=0 dirs=0 routes=0 reason=no-frontend');
  }
  process.exit(0);
}

// Multi-surface loop: iterate over all playwright surfaces
for (const surface of SURFACES) {
  // Update mutable state for this surface
  TEST_DIR = surface.testDir;
  FRONTEND_E2E_DIR = surface.testDir;
  FRONTEND_MODE = surface.frontendMode;
  FRONTEND_CONFIG_PATH = surface.runnerConfig || join(surface.path, 'playwright.config.ts');

  if (SURFACES.length > 1) {
    console.log(`\n── Surface: ${surface.name} (${surface.id}) → ${surface.testDir} ──`);
  }

  const features = scanFeatures();

  if (scan) {
    printScanTable(features);
    continue;
  }

  if (dryRun || generate) {
    printScanTable(features);
    generateTests(features, dryRun);
  }
}

if (scan) {
  process.exit(0);
}
