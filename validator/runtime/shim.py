"""Generation of the ``<home>/bin/livespec`` CLI shim (D-06)."""

from __future__ import annotations

import os
from pathlib import Path

from .errors import LiveSpecRuntimeError
from .home import RuntimeHome

SHIM_CORE_PATH = Path(__file__).with_name("shim_core.py")
SHIM_MODE = 0o755


def render_shim(python: str, home: Path) -> str:
    """Render the shim script text.

    The script is: a shebang naming the recorded interpreter, a generated-file
    notice, the verbatim source of ``shim_core.py`` (read as text, never imported,
    so the shim depends on the standard library only), then a footer recording the
    generated home and calling ``main``.

    Args:
        python: Absolute interpreter path recorded at install time.
        home: Runtime home the shim belongs to.

    Returns:
        The complete shim source.
    """
    core = SHIM_CORE_PATH.read_text(encoding="utf-8")
    header = f"#!{python}\n# Generated by `livespec runtime install`; do not edit.\n"
    footer = (
        f"\n\nGENERATED_HOME = {str(home)!r}\n\n"
        'if __name__ == "__main__":\n'
        "    raise SystemExit(main(GENERATED_HOME))\n"
    )
    return header + core + footer


# @spec FR-003: Shim on install — .specs/features/083-pinned-runtime-isolation/spec.md#fr-003
def write_shim(home: RuntimeHome, python: str) -> Path:
    """Atomically (re)write ``<home>/bin/livespec`` for ``python``.

    Args:
        home: Runtime home.
        python: Interpreter path (``sys.executable`` of the installing process).

    Returns:
        The shim path.

    Raises:
        LiveSpecRuntimeError: If the interpreter or home path contains whitespace,
            which a shebang line cannot carry portably.
    """
    check_shim_paths(home, python)
    home.shim.parent.mkdir(parents=True, exist_ok=True)
    temporary = home.shim.with_name(f".livespec.{os.getpid()}.tmp")
    # Write then chmod then rename so a concurrent caller never runs a partial shim.
    temporary.write_text(render_shim(python, home.root), encoding="utf-8")
    temporary.chmod(SHIM_MODE)
    os.replace(temporary, home.shim)
    return home.shim


def check_shim_paths(home: RuntimeHome, python: str) -> None:
    """Validate shim inputs before any install write (D-06, validation first).

    Args:
        home: Runtime home.
        python: Interpreter path.

    Raises:
        LiveSpecRuntimeError: If either path contains whitespace.
    """
    for label, value in (("interpreter", python), ("runtime home", str(home.root))):
        if any(char.isspace() for char in value):
            raise LiveSpecRuntimeError(f"{label} path contains whitespace (refused): {value}")
