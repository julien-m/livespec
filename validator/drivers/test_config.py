# Top-level orchestration
# ---------------------------------------------------------------------------


@dataclass
class TestConfigPlan:
    """Result of ``generate_test_config`` ready to be written to disk.

    Attributes:
        files: Ordered list of files to create or patch.
        runner: Stack-specific test runner name (e.g. ``pytest``, ``vitest``).
        snapshot_lib: Snapshot library if known, otherwise ``"none"``.
        threshold: Configured coverage threshold (percentage 0-100).
    """

    files: list[GeneratedFile] = field(default_factory=list[GeneratedFile])
    runner: str = ""
    snapshot_lib: str = "none"
    threshold: float = DEFAULT_THRESHOLD


def generate_test_config(
    driver: DriverManifest,
    project_root: Path,
    threshold: float = DEFAULT_THRESHOLD,
) -> TestConfigPlan:
    """Build the full test config plan for a project's primary driver.

    Args:
        driver: The detected primary ``DriverManifest``.
        project_root: Repository root (kept for future driver-specific decisions
            such as detecting `pnpm-workspace.yaml` polyglots).
        threshold: Coverage percentage to enforce. Defaults to
            :data:`DEFAULT_THRESHOLD`.

    Returns:
        A :class:`TestConfigPlan` with the coverage config + CI workflow files
        and metadata used to update the conventions ``testing`` domain.

    Raises:
        ValueError: If ``threshold`` is outside the (0, 100] range.
    """
    if not 0.0 < threshold <= 100.0:
        raise ValueError(f"threshold must be in (0, 100], got {threshold}")
    # project_root is reserved for future polyglot heuristics; reference it so
    # static checkers do not flag it as unused while keeping the public API
    # forward-compatible (EC-003 will refine the primary-driver pick here).
    _ = project_root
    plan = TestConfigPlan(threshold=threshold)
    generator = _GENERATORS.get(driver.name)
    if generator is not None:
        plan.files.append(generator(threshold))
    plan.files.append(generate_ci_workflow(driver))
    plan.runner = _runner_for(driver)
    plan.snapshot_lib = _snapshot_lib_for(driver)
    return plan


def _runner_for(driver: DriverManifest) -> str:
    """Infer the user-facing test runner name from a driver manifest."""
    coverage = driver.coverage
    command = (coverage.command or coverage.script or "") if coverage else ""
    lowered = command.lower()
    if "pytest" in lowered:
        return "pytest"
    if "vitest" in lowered:
        return "vitest"
    if "jest" in lowered:
        return "jest"
    if "swift test" in lowered:
        return "swift test"
    if "go test" in lowered:
        return "go test"
    if "cargo" in lowered or "tarpaulin" in lowered:
        return "cargo test"
    if "gradle" in lowered:
        return "gradle test"
    if "mvn" in lowered:
        return "mvn test"
    return driver.name


def _snapshot_lib_for(driver: DriverManifest) -> str:
    """Infer a snapshot library label from the driver's snapshot capability."""
    snapshots = driver.snapshots
    if snapshots is None:
        return "none"
    command = (snapshots.command or snapshots.script or "").lower()
    if "syrupy" in command or "pytest" in command:
        return "syrupy"
    if "vitest" in command or "jest" in command:
        return "vitest snapshot"
    if "swift" in command:
        return "swift-snapshot-testing"
    return "custom"


# ---------------------------------------------------------------------------
# Conventions index update
# ---------------------------------------------------------------------------


_CONV_BEGIN = "<!-- livespec:testing:begin -->"
_CONV_END = "<!-- livespec:testing:end -->"


def update_conventions_testing_domain(
    plan: TestConfigPlan,
    driver: DriverManifest,
    conventions_index: Path,
) -> bool:
    """Insert or replace the ``testing`` domain block in ``.conventions/index.md``.

    Args:
        plan: The plan returned by :func:`generate_test_config`.
        driver: The driver used for that plan (used for the ``Stack`` label).
        conventions_index: Absolute path to ``.conventions/index.md``.

    Returns:
        ``True`` if the file was created or rewritten, ``False`` if the
        conventions index does not exist (graceful no-op).
    """
    if not conventions_index.is_file():
        return False
    block = _render_conventions_block(plan, driver)
    original = conventions_index.read_text(encoding="utf-8")
    if _CONV_BEGIN in original and _CONV_END in original:
        before, _, rest = original.partition(_CONV_BEGIN)
        _, _, after = rest.partition(_CONV_END)
        new_text = f"{before.rstrip()}\n\n{block}\n{after.lstrip()}"
    else:
        suffix = "" if original.endswith("\n") else "\n"
        new_text = f"{original}{suffix}\n{block}\n"
    conventions_index.write_text(new_text, encoding="utf-8")
    return True


def _render_conventions_block(plan: TestConfigPlan, driver: DriverManifest) -> str:
    """Render the conventions ``testing`` domain block for the index file."""
    coverage_files = ", ".join(
        str(f.path) for f in plan.files if f.path != CI_WORKFLOW_PATH
    ) or "(none)"
    return (
        f"{_CONV_BEGIN}\n"
        "## testing [test, coverage, snapshot, ci]\n"
        f"- Stack: {driver.name}\n"
        f"- Runner: {plan.runner}\n"
        f"- Coverage threshold: {plan.threshold:g}%\n"
        f"- Snapshot library: {plan.snapshot_lib}\n"
        f"- Coverage config: {coverage_files}\n"
        f"- CI workflow: {CI_WORKFLOW_PATH}\n"
        "- Run locally: `livespec spec.test`\n"
        f"{_CONV_END}"
    )


# ---------------------------------------------------------------------------
# File materialization
# ---------------------------------------------------------------------------


@dataclass
class WriteOutcome:
    """Outcome of materializing a single ``GeneratedFile``.

    Attributes:
        path: Project-root-relative path that was processed.
        action: ``"created"``, ``"patched"``, or ``"skipped"``.
        reason: Optional reason — e.g. ``"file exists"`` for skipped writes.
    """

    path: Path
    action: Literal["created", "patched", "skipped"]
    reason: str = ""


def materialize_files(
    files: list[GeneratedFile],
    project_root: Path,
    *,
    force: bool = False,
) -> list[WriteOutcome]:
    """Write the planned files to disk honoring each entry's mode.

    Args:
        files: ``GeneratedFile`` entries returned by :func:`generate_test_config`.
        project_root: Repository root used as the base for relative paths.
        force: When ``True``, ``skip_if_exists`` files are still overwritten.
            ``patch_section`` files are always patched in place; this flag does
            not change their behavior.

    Returns:
        One :class:`WriteOutcome` per entry, in the same order as ``files``.
    """
    outcomes: list[WriteOutcome] = []
    for entry in files:
        target = project_root / entry.path
        target.parent.mkdir(parents=True, exist_ok=True)
        if entry.mode == "create":
            target.write_text(entry.content, encoding="utf-8")
            outcomes.append(WriteOutcome(entry.path, "created"))
            continue
        if entry.mode == "skip_if_exists":
            if target.exists() and not force:
                outcomes.append(
                    WriteOutcome(entry.path, "skipped", "file exists"),
                )
                continue
            target.write_text(entry.content, encoding="utf-8")
            outcomes.append(WriteOutcome(entry.path, "created"))
            continue
        # patch_section
        marker = entry.section_marker or entry.path.name
        outcomes.append(_patch_section(target, entry.content, marker, entry.path))
    return outcomes


def _patch_section(
    target: Path,
    body: str,
    marker: str,
    rel_path: Path,
) -> WriteOutcome:
    """Insert/replace a ``# livespec:testing:<marker>`` block in ``target``.

    Args:
        target: Absolute path of the file to patch.
        body: Content placed between the begin/end markers.
        marker: Stable identifier so multiple LiveSpec blocks can coexist.
        rel_path: Project-root-relative path used in the returned outcome.

    Returns:
        A :class:`WriteOutcome` describing whether the file was created (no
        prior content) or patched in place.
    """
    begin = f"# livespec:testing:{marker}:begin"
    end = f"# livespec:testing:{marker}:end"
    block = f"{begin}\n{body.rstrip()}\n{end}\n"
    if not target.exists():
        target.write_text(block, encoding="utf-8")
        return WriteOutcome(rel_path, "created")
    original = target.read_text(encoding="utf-8")
    if begin in original and end in original:
        before, _, rest = original.partition(begin)
        _, _, after = rest.partition(end)
        new_text = f"{before.rstrip()}\n\n{block}{after.lstrip()}"
    else:
        suffix = "" if original.endswith("\n") else "\n"
        new_text = f"{original}{suffix}\n{block}"
    target.write_text(new_text, encoding="utf-8")
    return WriteOutcome(rel_path, "patched")


# ---------------------------------------------------------------------------
# Primary-driver selection (EC-003 — polyglot)
# ---------------------------------------------------------------------------


def pick_primary_driver(
    drivers: list[DriverManifest],
    project_root: Path,
) -> DriverManifest | None:
    """Pick the driver matching the most files at the repository root.

    Args:
        drivers: Drivers already filtered to those matching the project root.
        project_root: Repository root used to resolve detect glob patterns.

    Returns:
        The driver matching the highest number of detect files (ties broken by
        the input order — built-ins after custom, alphabetical), or ``None``
        when ``drivers`` is empty.
    """
    if not drivers:
        return None
    if len(drivers) == 1:
        return drivers[0]

    def _score(driver: DriverManifest) -> int:
        total = 0
        for pattern in driver.detect.files:
            total += sum(1 for _ in project_root.glob(pattern))
        return total

    best = drivers[0]
    best_score = _score(best)
    for candidate in drivers[1:]:
        score = _score(candidate)
        if score > best_score:
            best = candidate
            best_score = score
    return best
