def python_config(threshold: float) -> GeneratedFile:
    """Return the ``pyproject.toml`` patch enabling coverage gating.

    Args:
        threshold: Minimum coverage percentage to enforce.

    Returns:
        A ``GeneratedFile`` patching the ``[tool.coverage.report]`` table.
    """
    body = (
        "[tool.coverage.report]\n"
        f"fail_under = {threshold:g}\n"
        "show_missing = true\n"
    )
    return GeneratedFile(
        path=Path("pyproject.toml"),
        content=body,
        mode="patch_section",
        section_marker="python-coverage",
    )


def typescript_config(threshold: float) -> GeneratedFile:
    """Return the ``vitest.config.ts`` patch enabling coverage thresholds.

    Args:
        threshold: Minimum coverage percentage to enforce on lines.

    Returns:
        A ``GeneratedFile`` patching the vitest coverage section. The patch is
        valid TypeScript so the snippet can be inlined with `// livespec` markers.
    """
    body = (
        "// LiveSpec-managed vitest coverage thresholds.\n"
        "export const livespecCoverage = {\n"
        "  provider: 'v8',\n"
        "  reporter: ['text', 'lcov'],\n"
        "  thresholds: {\n"
        f"    lines: {threshold:g},\n"
        f"    statements: {threshold:g},\n"
        f"    functions: {threshold:g},\n"
        f"    branches: {threshold:g},\n"
        "  },\n"
        "};\n"
    )
    return GeneratedFile(
        path=Path("vitest.config.ts"),
        content=body,
        mode="patch_section",
        section_marker="typescript-coverage",
    )


def swift_config(threshold: float) -> GeneratedFile:
    """Return a Swift coverage config snippet (XCTest + xccov)."""
    body = (
        "# LiveSpec-managed Swift coverage gate (feature 026).\n"
        "# Run `swift test --enable-code-coverage` then check this threshold via xccov.\n"
        f"threshold: {threshold:g}\n"
        "report: build/coverage.xcresult\n"
    )
    return GeneratedFile(
        path=Path(".swift-coverage.yml"),
        content=body,
        mode="skip_if_exists",
    )


def go_config(threshold: float) -> GeneratedFile:
    """Return a Go coverage config snippet."""
    body = (
        "# LiveSpec-managed Go coverage gate (feature 026).\n"
        "# Use with `go test -coverprofile=coverage.out ./...`.\n"
        f"threshold: {threshold:g}\n"
        "profile: coverage.out\n"
    )
    return GeneratedFile(
        path=Path(".go-coverage.yml"),
        content=body,
        mode="skip_if_exists",
    )


def rust_config(threshold: float) -> GeneratedFile:
    """Return a Rust coverage config snippet (cargo-tarpaulin)."""
    body = (
        "# LiveSpec-managed cargo-tarpaulin config (feature 026).\n"
        "[report]\n"
        "out = [\"Lcov\"]\n"
        "[run]\n"
        f"fail-under = {threshold:g}\n"
    )
    return GeneratedFile(
        path=Path("tarpaulin.toml"),
        content=body,
        mode="skip_if_exists",
    )


def jvm_config(threshold: float) -> GeneratedFile:
    """Return a JaCoCo coverage config snippet."""
    body = (
        "// LiveSpec-managed JaCoCo coverage gate (feature 026).\n"
        "// Apply via build.gradle(.kts): `apply from: 'jacoco-livespec.gradle'`.\n"
        "jacocoTestCoverageVerification {\n"
        "    violationRules {\n"
        "        rule {\n"
        "            limit {\n"
        f"                minimum = {threshold / 100:.2f}\n"
        "            }\n"
        "        }\n"
        "    }\n"
        "}\n"
    )
    return GeneratedFile(
        path=Path("jacoco-livespec.gradle"),
        content=body,
        mode="skip_if_exists",
    )


_GENERATORS: dict[str, Callable[[float], GeneratedFile]] = {
    "python": python_config,
    "typescript": typescript_config,
    "swift": swift_config,
    "go": go_config,
    "rust": rust_config,
    "jvm": jvm_config,
}


