"""Generate per-stack test config files from a detected DriverManifest.

Feature 026: conventions propagation by stack. Given the primary driver detected
for a project, produce the files that wire the test runner's coverage gate plus
a CI workflow that calls ``livespec spec.test``. The conventions index is also
updated with a ``testing`` domain entry so downstream AI tools know what is
configured.
"""

# @spec FR-001: generate_test_config returns list[GeneratedFile] per stack.
# @spec FR-002: Per-stack config generators (python/typescript/swift/go/rust/jvm).
# @spec FR-003: generate_ci_workflow returns YAML calling livespec spec.test.
# @spec FR-004: update_conventions_testing_domain patches .conventions/index.md.
# @spec AC-001: Detected supported stack -> coverage config in runner config file.
# @spec AC-002: Unsupported stack -> note + skip without blocking.
# @spec AC-003: Generated CI calls `livespec spec.test`, includes install step.
# @spec AC-004: Default coverage threshold 70 (configurable).
# @spec AC-005: testing entry added/updated in .conventions/index.md.
# @spec AC-006: Conventions update reused by spec.refresh-conventions.
# @spec AC-007: Caller can list generated files in completion summary.
# @spec AC-008: Generated config does not break existing project files.
# @spec EC-001: vitest.config.ts existing -> patch coverage section, no overwrite.
# @spec EC-002: .github/workflows/test.yml existing -> skip, do not overwrite.
# @spec EC-003: Polyglot project -> primary driver = most matched files.
# @spec EC-004: Missing .github/ directory created when writing the workflow.

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import Literal

from .schemas import DriverManifest

WriteMode = Literal["create", "patch_section", "skip_if_exists"]

DEFAULT_THRESHOLD = 70.0


@dataclass(frozen=True)
class GeneratedFile:
    """A file to materialize during ``/spec.init`` or ``livespec init test-config``.

    Attributes:
        path: Project-root-relative path of the file to write.
        content: File contents (or section body when ``mode == 'patch_section'``).
        mode: Write strategy. ``create`` always writes; ``skip_if_exists`` skips
            when the file already exists; ``patch_section`` inserts/replaces the
            block delimited by LiveSpec markers when the file already exists.
        section_marker: Stable identifier injected as ``# livespec:testing:<marker>``
            anchors when patching. Required for ``patch_section`` files.
    """

    path: Path
    content: str
    mode: WriteMode = "create"
    section_marker: str | None = None


# ---------------------------------------------------------------------------
# CI workflow
# ---------------------------------------------------------------------------


CI_WORKFLOW_PATH = Path(".github/workflows/test.yml")


def generate_ci_workflow(driver: DriverManifest) -> GeneratedFile:
    """Render a GitHub Actions workflow that runs ``livespec spec.test``.

    Args:
        driver: Detected primary driver. Currently used only to decide which
            language toolchain step to add before LiveSpec is installed.

    Returns:
        A ``GeneratedFile`` for ``.github/workflows/test.yml`` with
        ``mode='skip_if_exists'`` so existing CI is never overwritten.
    """
    setup_step = _ci_setup_step(driver.name)
    content = (
        "# Generated by LiveSpec (feature 026). Calls `livespec spec.test`\n"
        "# so the test driver orchestration is exercised in CI.\n"
        "name: tests\n"
        "on:\n"
        "  push:\n"
        "  pull_request:\n"
        "jobs:\n"
        "  test:\n"
        "    runs-on: ubuntu-latest\n"
        "    steps:\n"
        "      - uses: actions/checkout@v4\n"
        f"{setup_step}"
        "      - name: Install LiveSpec\n"
        "        run: pip install livespec-validator\n"
        "      - name: Run LiveSpec test orchestration\n"
        "        run: livespec spec.test\n"
    )
    return GeneratedFile(path=CI_WORKFLOW_PATH, content=content, mode="skip_if_exists")


def _ci_setup_step(driver_name: str) -> str:
    """Return the language-specific setup step inserted before LiveSpec install.

    Args:
        driver_name: Driver manifest name. Unknown drivers fall back to a Python
            setup step (LiveSpec itself is a Python package).

    Returns:
        YAML fragment (already indented with six spaces) ending with a newline.
    """
    if driver_name == "typescript":
        return (
            "      - uses: actions/setup-node@v4\n"
            "        with:\n"
            "          node-version: '20'\n"
            "      - uses: actions/setup-python@v5\n"
            "        with:\n"
            "          python-version: '3.11'\n"
        )
    if driver_name == "go":
        return (
            "      - uses: actions/setup-go@v5\n"
            "        with:\n"
            "          go-version: '1.22'\n"
            "      - uses: actions/setup-python@v5\n"
            "        with:\n"
            "          python-version: '3.11'\n"
        )
    if driver_name == "rust":
        return (
            "      - uses: dtolnay/rust-toolchain@stable\n"
            "      - uses: actions/setup-python@v5\n"
            "        with:\n"
            "          python-version: '3.11'\n"
        )
    if driver_name == "jvm":
        return (
            "      - uses: actions/setup-java@v4\n"
            "        with:\n"
            "          distribution: temurin\n"
            "          java-version: '21'\n"
            "      - uses: actions/setup-python@v5\n"
            "        with:\n"
            "          python-version: '3.11'\n"
        )
    if driver_name == "swift":
        return (
            "      - uses: swift-actions/setup-swift@v2\n"
            "      - uses: actions/setup-python@v5\n"
            "        with:\n"
            "          python-version: '3.11'\n"
        )
    # Python and unknown drivers — Python is enough since LiveSpec runs on it.
    return (
        "      - uses: actions/setup-python@v5\n"
        "        with:\n"
        "          python-version: '3.11'\n"
    )


